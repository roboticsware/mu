#!/usr/bin/env python3
"""Update the copy of user libs (pgzhelper, nethelper, picozero, espzero ...).

User libs are mirrored from their repositories into the local mu resources
directory to make them easily accessible or installable.

Usage:
    python update_user_libs.py pgzhelper
    python update_user_libs.py nethelper
    python update_user_libs.py picozero
    python update_user_libs.py espzero
    python update_user_libs.py all
"""
import argparse
import base64
import json
import os
import shutil
import subprocess
import sys
from urllib.parse import urljoin
from urllib.request import Request, build_opener

opener = build_opener()
opener.addheaders = [("User-Agent", "Mu-User-Libs-Updater/1.0")]

LIBS = {
    "pgzhelper": {
        "repo_url": "https://api.github.com/repos/roboticsware/pgzhelper/",
        "dest": "mu/resources/pygamezero/pgzhelper.py",
        "remote_path": "pgzhelper/pgzhelper.py",
        "header": '''"""pgzhelper - Enhance Pygame Zero with additional capabilities.

This module is directly copied from

    https://github.com/roboticsware/pgzhelper

at revision {sha}
and used under CC0.

"""
# flake8: noqa: E501
''',
    },
    "nethelper": {
        "repo_url": "https://api.github.com/repos/roboticsware/nethelper/",
        "dest": "mu/resources/pygamezero/nethelper.py",
        "remote_path": "nethelper.py",
        "header": '''"""

This module is directly copied from

    https://github.com/roboticsware/nethelper

at revision {sha}
and used under CC0.

"""
# flake8: noqa: E501
''',
    },
    "picozero": {
        "repo_url": "https://api.github.com/repos/roboticsware/picozero/",
        "dest": "mu/resources/pico/picozero.py",
        "remote_path": "picozero/picozero.py",
        "header": "",
    },
    "espzero": {
        "repo_url": "https://api.github.com/repos/roboticsware/espzero/",
        "dest": "mu/resources/esp32",
        "header": """\
# This file is part of espzero, automatically synced from
# https://github.com/roboticsware/espzero at revision {sha}.
# Do not edit this file directly — run update_user_libs.py espzero instead.

""",
    },
}


def read_json(url):
    """Download and decode a JSON resource from the given URL."""
    req = Request(url)
    resp = opener.open(req)
    charset = resp.headers.get_content_charset() or "utf-8"
    data = resp.read().decode(charset)
    return json.loads(data)


def get_tree(repo_url):
    """Download the repository tree, returning a decoded JSON structure."""
    print("Downloading repository tree...")
    url = urljoin(repo_url, "git/trees/HEAD?recursive=1")
    return read_json(url)


def autopep8_file(path):
    """Run autopep8 on target file if autopep8 is installed."""
    if shutil.which("autopep8"):
        print(f"Running autopep8 on {path}")
        subprocess.check_call(["autopep8", "-i", path])


def update_single_file(name):
    """Update single file library (pgzhelper, nethelper, picozero)."""
    cfg = LIBS[name]
    tree = get_tree(cfg["repo_url"])
    target_path = cfg["remote_path"]

    for item in tree.get("tree", []):
        if item.get("path") == target_path:
            blob_url = item["url"]
            break
    else:
        raise ValueError(f"Could not find {target_path} in repository.")

    print(f"Downloading {name} ({target_path})...")
    blob = read_json(blob_url)
    data = base64.b64decode(blob["content"]).decode("utf-8")

    sha = tree["sha"]
    header = cfg["header"].format(sha=sha) if cfg["header"] else ""

    dest = cfg["dest"]
    dest_dir = os.path.dirname(dest)
    if dest_dir and not os.path.exists(dest_dir):
        os.makedirs(dest_dir)

    with open(dest, "w", encoding="utf-8") as f:
        f.write(header + data)

    print(f"Updated {name} ({dest}) to revision {sha[:7]}")
    autopep8_file(dest)


def update_espzero():
    """Download all .py files from the espzero repo and write them to ESPZERO_DEST.

    Preserves the package directory structure (e.g. profiles/ subdir).
    Prepends ESPZERO_HEADER to every file so the source revision is traceable.
    """
    cfg = LIBS["espzero"]
    tree = get_tree(cfg["repo_url"])
    sha = tree["sha"]
    header = cfg["header"].format(sha=sha)
    dest_root = cfg["dest"]

    py_blobs = [
        f
        for f in tree.get("tree", [])
        if f.get("type") == "blob" and f.get("path", "").endswith(".py")
    ]

    for entry in py_blobs:
        rel_path = entry["path"]  # e.g. '_hal.py' or 'profiles/auto.py'
        dest_path = os.path.join(dest_root, rel_path)

        dest_dir = os.path.dirname(dest_path)
        if dest_dir and not os.path.exists(dest_dir):
            os.makedirs(dest_dir)
            print("Created directory:", dest_dir)

        print("Downloading", rel_path, "...")
        blob = read_json(entry["url"])
        data = base64.b64decode(blob["content"]).decode("utf-8")

        with open(dest_path, "w", encoding="utf-8") as f:
            f.write(header + data)

        print("  ->", dest_path)

    print(f"\nespzero updated to revision {sha[:7]} ({len(py_blobs)} files)")


def normalize_target(target):
    """Normalize input target name (allow .py suffix)."""
    t = target.lower()
    if t.endswith(".py"):
        t = t[:-3]
    return t


def update_target(target):
    """Dispatch update for given target."""
    t = normalize_target(target)
    if t == "espzero":
        update_espzero()
    elif t in LIBS:
        update_single_file(t)
    elif t == "all":
        for name in LIBS:
            update_target(name)
    else:
        valid_targets = ", ".join(list(LIBS.keys()) + ["all"])
        raise ValueError(f"Unknown library '{target}'. Valid options: {valid_targets}")


def main():
    parser = argparse.ArgumentParser(
        description="Update user libraries for Mu Editor from their repositories."
    )
    parser.add_argument(
        "library",
        nargs="?",
        default=None,
        help="Target library to update (pgzhelper, nethelper, picozero, espzero, or all)",
    )
    args = parser.parse_args()

    if not args.library:
        parser.print_help()
        sys.exit(1)

    try:
        update_target(args.library)
    except Exception as exc:
        print(f"Error: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
